"""Optional unsubscribe web app (deploy this where it can be reached).

Implements the HTTPS target for the List-Unsubscribe links:

    GET  /unsubscribe?email=...&token=...   → human clicks the link
    POST /unsubscribe                      → RFC 8058 one-click unsubscribe
                                             (body: List-Unsubscribe=One-Click)

Both verify the per-recipient HMAC token generated by unsubscribe.py
and append the address to the suppression CSV, which the campaign
always checks before sending. The same secret must be set in the
campaign .env (UNSUBSCRIBE_SECRET).

Run locally for testing:
    pip install flask
    python unsubscribe_server.py

Deploy anywhere that can run Flask (Render, Railway, a small VPS) and
set UNSUBSCRIBE_BASE_URL in your .env to its public URL, e.g.:
    UNSUBSCRIBE_BASE_URL=https://your-unsubscribe-app.onrender.com

If deployed on a different machine than the campaign, copy the
resulting suppression.csv back (or host the server on the same host /
shared volume) — the campaign only reads its local SUPPRESSION_FILE.
"""

import os
import sys
from pathlib import Path

# Make the project modules importable when started from elsewhere.
sys.path.insert(0, str(Path(__file__).parent))

from suppression import add_to_suppression  # noqa: E402
from unsubscribe import verify_token  # noqa: E402

UNSUBSCRIBE_SECRET = os.getenv("UNSUBSCRIBE_SECRET", "")
SUPPRESSION_FILE = os.getenv("SUPPRESSION_FILE", "suppression.csv")

CONFIRMATION_PAGE = """<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Unsubscribed</title></head>
<body style="font-family: Arial, sans-serif; background:#f4f4f4; padding:40px;">
<div style="max-width:600px; margin:auto; background:white; padding:30px; border-radius:10px;">
<h1 style="color:#2563eb;">You have been unsubscribed</h1>
<p>You will not receive any further campaign emails from us.</p>
<p style="color:gray;font-size:12px;">If this was a mistake, contact us to re-subscribe.</p>
</div></body></html>"""

ERROR_PAGE = """<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Invalid unsubscribe link</title></head>
<body style="font-family: Arial, sans-serif; background:#f4f4f4; padding:40px;">
<div style="max-width:600px; margin:auto; background:white; padding:30px; border-radius:10px;">
<h1 style="color:#dc2626;">Invalid unsubscribe link</h1>
<p>This link is expired or invalid. Please contact us directly.</p>
</div></body></html>"""


def _handle_unsubscribe(email, token):
    """Verify the token and suppress the address.

    Returns:
        bool: True if the request was valid and processed.
    """
    if not UNSUBSCRIBE_SECRET:
        print("UNSUBSCRIBE_SECRET is not set — refusing to process clicks.")
        return False

    if not email or not verify_token(email, token, UNSUBSCRIBE_SECRET):
        return False

    add_to_suppression(
        SUPPRESSION_FILE, email, reason="Unsubscribed via link", source="unsubscribe-link"
    )

    return True


def create_app():
    """Build the Flask app (lazy import so Flask stays optional)."""
    try:
        from flask import Flask, request
    except ImportError:
        raise SystemExit(
            "The unsubscribe server requires Flask. "
            "Install it with: pip install flask"
        )

    app = Flask(__name__)

    @app.route("/unsubscribe", methods=["GET", "POST"])
    def unsubscribe():
        email = (request.args.get("email") or "").strip()
        token = (request.args.get("token") or "").strip()

        if _handle_unsubscribe(email, token):
            return CONFIRMATION_PAGE, 200

        return ERROR_PAGE, 400

    @app.route("/healthz")
    def healthz():
        return "ok", 200

    return app


if __name__ == "__main__":
    create_app().run(
        host=os.getenv("HOST", "127.0.0.1"),
        port=int(os.getenv("PORT", "5000")),
    )
